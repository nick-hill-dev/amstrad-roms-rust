/// Return the eight pixel rows of character `code`.
pub fn glyph(code: u8) -> [u8; 8] { FONT[code as usize] }

/// Render a glyph as eight strings of `#` and `.` (for documentation and tests).
pub fn glyph_art(code: u8) -> [String; 8] {
    let g = FONT[code as usize];
    core::array::from_fn(|row| (0..8).map(|bit| if g[row] & (0x80 >> bit) != 0 { '#' } else { '.' }).collect())
}

